"""PreToolUse guard for AI agents (Claude Code). Exit code 2 blocks the tool call and tells the agent why.

Rules (see AGENTS.md):
1. The photos on "Suffering in detail" (site/img/bild-08 … bild-21) are never opened or viewed.
2. site/ is generated. Change the sources (content/, tools/) and rebuild instead of editing site/ by hand.
3. No force push, no push to main, no skipped git hooks, no history rewrite on shared branches.
4. No secrets: .env files and key files are neither read nor written.
"""
import json, re, sys

PROTECTED = re.compile(r'bild-(0[89]|1\d|2[01])\b')
GENERATED_OK = re.compile(r'(^|/)site/(img/|fonts/|favicon\.svg$)')
SECRET_FILE = re.compile(r'(^|/)(\.env(\..*)?|.*\.(pem|key|p12|pfx)|id_(rsa|ed25519)(\.pub)?|\.dev\.vars)$')


def block(why):
    print(f'Blocked by .claude/hooks/guard.py: {why}', file=sys.stderr)
    sys.exit(2)


try:
    data = json.load(sys.stdin)
except ValueError:
    sys.exit(0)
tool, inp = data.get('tool_name', ''), data.get('tool_input', {}) or {}
path = str(inp.get('file_path') or inp.get('notebook_path') or inp.get('path') or '').replace('\\', '/')

if tool in ('Read', 'Edit', 'Write', 'NotebookEdit', 'MultiEdit'):
    if PROTECTED.search(path):
        block('the "Suffering in detail" photos are never viewed. Their descriptions are in content/alt/*.json (keys 8 to 21).')
    if SECRET_FILE.search(path):
        block('secret files (.env, keys) stay out of reach of agents.')
    if tool != 'Read' and re.search(r'(^|/)site/', path) and not GENERATED_OK.search(path):
        block('site/ is generated by tools/build.py. Edit content/ or tools/ and run `python tools/build_all.py`.')

if tool == 'Bash':
    cmd = str(inp.get('command', ''))
    if PROTECTED.search(cmd) and not re.match(r'\s*git\s', cmd):
        block('the "Suffering in detail" photos are never opened, converted or displayed.')
    for part in re.split(r'&&|\|\||;|\n', cmd):
        p = part.strip()
        if re.match(r'git\s+push\b', p):
            if re.search(r'\s(-f|--force|--force-with-lease|--mirror|--delete|-d)\b|\s\+\S', p):
                block('no force push or branch deletion. Ask the user (an owner) to do it.')
            if re.search(r'\s(\S+:)?(refs/heads/)?(main|master)\s*$', p):
                block('main is published automatically. Changes reach main only through a reviewed pull request.')
        if re.match(r'git\s+(commit|push|merge|rebase)\b.*--no-verify', p):
            block('git hooks are not skipped.')
        if re.match(r'git\s+(filter-branch|filter-repo)\b', p):
            block('history is not rewritten.')
        if re.match(r'git\s+config\b.*\b(user\.(name|email)|core\.hooksPath)', p):
            block('git identity and hooks are left as configured.')
sys.exit(0)
